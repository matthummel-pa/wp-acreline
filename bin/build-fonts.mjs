#!/usr/bin/env node
// Writes resources/css/fonts.css: self-hosted @font-face rules for every
// Customizer font (app/Support/Typography.php), latin + latin-ext only.
// Source: Fontsource packages in devDependencies. Run after updating them:
//   node bin/build-fonts.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// [family, package, css files]
const fonts = [
  ['Inter', '@fontsource-variable/inter', ['wght.css', 'wght-italic.css']],
  ['Plus Jakarta Sans', '@fontsource-variable/plus-jakarta-sans', ['wght.css', 'wght-italic.css']],
  ['DM Sans', '@fontsource-variable/dm-sans', ['wght.css', 'wght-italic.css']],
  ['Manrope', '@fontsource-variable/manrope', ['wght.css']],
  ['Montserrat', '@fontsource-variable/montserrat', ['wght.css', 'wght-italic.css']],
  ['Poppins', '@fontsource/poppins', ['400.css', '500.css', '600.css', '700.css', '400-italic.css']],
  ['Source Sans 3', '@fontsource-variable/source-sans-3', ['wght.css', 'wght-italic.css']],
  ['Nunito Sans', '@fontsource-variable/nunito-sans', ['wght.css', 'wght-italic.css']],
  ['Outfit', '@fontsource-variable/outfit', ['wght.css']],
  ['Lato', '@fontsource/lato', ['400.css', '700.css', '400-italic.css']],
];

const subsets = /-latin(-ext)?-[\w-]+ \*\//;
let out = '/* Generated by bin/build-fonts.mjs. Do not edit by hand. */\n';

for (const [family, pkg, files] of fonts) {
  for (const file of files) {
    const css = readFileSync(join(root, 'node_modules', pkg, file), 'utf8');
    const blocks = css.split(/(?=\/\* )/).filter((b) => subsets.test(b.split('\n')[0]));
    if (!blocks.length) throw new Error(`No latin faces in ${pkg}/${file}`);
    for (const block of blocks) {
      out += block
        .replace(/font-family: '[^']+'/, `font-family: '${family}'`)
        .replace(/url\(\.\/files\//g, `url(${pkg}/files/`)
        .trimEnd() + '\n';
    }
  }
}

writeFileSync(join(root, 'resources/css/fonts.css'), out);
console.log('resources/css/fonts.css written');
